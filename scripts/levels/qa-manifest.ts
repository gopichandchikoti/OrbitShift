/**
 * Writes docs/LEVEL_QA.md: one row per level, 120 in all. Automated verification is computed from the data here.
 * Manual play-through status comes from qa/manual-playthroughs.json, which only a person edits: this script never
 * invents a "passed". Until someone records a result, every level reads "not played by a person".
 *
 *   npm run levels:qa
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { familiesOf } from '../../src/game/levels/audit';
import { LEVELS } from '../../src/game/levels/catalog';
import { CHAPTERS } from '../../src/game/levels/chapters';
import { levelSchema } from '../../src/game/levels/schema';
import { validateLevel } from '../../src/game/levels/validate';
import { verifySolution } from '../../src/game/levels/verify';

interface ManualEntry {
  status: 'passed' | 'failed' | 'needs-work';
  tester?: string;
  date?: string;
  device?: string;
  notes?: string;
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const manualFile = join(root, 'qa', 'manual-playthroughs.json');
const manual: Record<string, ManualEntry> = existsSync(manualFile)
  ? (JSON.parse(readFileSync(manualFile, 'utf8')) as Record<string, ManualEntry>)
  : {};

function automated(id: number): string {
  const level = LEVELS[id - 1];
  if (!level) return 'MISSING';
  const schema = levelSchema.safeParse(level).success;
  const structure = validateLevel(level).length === 0;
  const replay = verifySolution(level).ok;
  return schema && structure && replay ? 'pass' : `FAIL (${[!schema && 'schema', !structure && 'geometry', !replay && 'replay'].filter(Boolean).join(', ')})`;
}

function manualCell(id: number): string {
  const entry = manual[String(id)];
  if (!entry) return 'not played by a person';
  const who = [entry.tester, entry.device, entry.date].filter(Boolean).join(', ');
  return `${entry.status}${who ? ` (${who})` : ''}${entry.notes ? `: ${entry.notes}` : ''}`;
}

const rows = LEVELS.map((level) => {
  const families = [...familiesOf(level)].sort().join(', ') || 'none';
  const cells = [
    level.id,
    `${level.chapter}.${level.index}`,
    level.name,
    families,
    level.planets.length,
    level.solution.launchTicks.length,
    `${level.par.launches} / ${level.par.seconds}`,
    (level.solution.totalTicks / 60).toFixed(1),
    Math.round((level.solution.minWindow / 60) * 1000),
    `${level.solution.shards}/${level.collectibles.filter((c) => c.kind === 'shard').length}`,
    automated(level.id),
    manualCell(level.id),
  ];
  return `| ${cells.join(' | ')} |`;
});

const passed = LEVELS.filter((level) => automated(level.id) === 'pass').length;
const played = Object.values(manual).filter((entry) => entry.status === 'passed').length;

const lines = [
  '# Level QA manifest',
  '',
  'Generated by `npm run levels:qa`. Do not edit by hand: record manual results in `qa/manual-playthroughs.json`.',
  '',
  `- **Automated verification:** ${passed}/${LEVELS.length} levels pass (runtime schema, geometry and clearance checks, and a replay of`,
  '  the recorded winning route through the real simulation that must finish with three stars).',
  `- **Played through by a person:** ${played}/${LEVELS.length}. Automated replay proves a winning route exists and is replayable; it does not`,
  '  prove a level is fun, fair or readable. Nothing below is marked as human-verified unless a person recorded it.',
  '',
  '| # | Ch.Lvl | Name | Mechanics | Planets | Launches | Par (launches / s) | Route (s) | Min window (ms) | Shards | Automated | Manual play-through |',
  '|--:|:--|:--|:--|--:|--:|:--|--:|--:|:--|:--|:--|',
  ...rows,
  '',
  '## Chapters',
  '',
  ...CHAPTERS.map((chapter) => `${chapter.id}. **${chapter.name}**: ${chapter.focus}`),
  '',
];

mkdirSync(join(root, 'docs'), { recursive: true });
mkdirSync(join(root, 'qa'), { recursive: true });
if (!existsSync(manualFile)) writeFileSync(manualFile, '{}\n');
writeFileSync(join(root, 'docs', 'LEVEL_QA.md'), `${lines.join('\n')}\n`);
console.log(`Wrote docs/LEVEL_QA.md: ${passed}/${LEVELS.length} automated pass, ${played}/${LEVELS.length} played by a person.`);
