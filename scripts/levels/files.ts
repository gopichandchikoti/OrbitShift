import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import type { Level } from '../../src/game/levels/types';

const here = dirname(fileURLToPath(import.meta.url));
export const DATA_DIR = join(here, '..', '..', 'src', 'game', 'levels', 'data');

export function chapterFile(chapter: number): string {
  return join(DATA_DIR, `chapter-${String(chapter).padStart(2, '0')}.ts`);
}

const HEADER = `// Generated by \`npm run levels:generate\` (scripts/levels). The solver verified every route recorded in
// \`solution\`; \`npm run levels:check\` replays all of them. Edit by hand only together with a re-check.
import type { Level } from '../types';

`;

export function writeChapter(chapter: number, levels: Level[]): void {
  mkdirSync(DATA_DIR, { recursive: true });
  const name = `CHAPTER_${String(chapter).padStart(2, '0')}`;
  writeFileSync(chapterFile(chapter), `${HEADER}export const ${name}: Level[] = ${JSON.stringify(levels, null, 2)};\n`);
}

/** Loads a generated chapter file, or an empty list when it has not been generated yet. */
export async function readChapter(chapter: number): Promise<Level[]> {
  const file = chapterFile(chapter);
  if (!existsSync(file) || readFileSync(file, 'utf8').length === 0) return [];
  const loaded: Record<string, Level[]> = await import(`${pathToFileURL(file).href}?t=${Date.now()}`);
  return Object.values(loaded)[0] ?? [];
}
